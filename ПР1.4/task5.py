# Задание 5. Даны вещественные числа a и b. Определите, принадлежит ли точка с
# координатами (a; b) заштрихованной области;

x, y = float(input()), float(input())

if -1 <= x <= 3 and -2 <= y <= 4:
    print(f"Точка с координатами ({x}, {y}) принадлежит квадрату")
else:
    print(f"Точка с координатами ({x}, {y}) не принадлежит квадрату")