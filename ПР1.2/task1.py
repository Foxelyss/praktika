# Задание 1. Создайте коллекцию(массив) размерностью 100. Добавьте в коллекцию числа в
# убывающем порядке, каждое число меньше предыдущего на 3;

array = []

for x in range(100, 0, -1):
    array.append(x * 3)

for y in range(10):
    for x in range(10):
        print(array[x + y * 10], end=', \t')
    print()
