# Задание 1. На различных мероприятиях команда стажировок регулярно разыгрывает призы в
# лотерею. Организаторы выбирают 10 случайных различных чисел от 1 до 32. Каждому
# участнику выдается лотерейный билет, на котором записаны 6 различных чисел от 1 до
# 32. Билет считается выигрышным, если в нем есть не менее 3 выбранных организаторами
# числа. Помогите Юле, напишите программу, которая будет сообщать, какие билеты
# выигрышные. Формат ввода. Данные должны браться из файла input.txt. В первой строке
# входных данных записаны 10 различных целых чисел ai (1≤ai≤32) — выбранные
# организаторами числа. Во второй строке записано одно целое число n (1≤n≤1000) —
# количество лотерейных билетов, выданных на мероприятии. В каждой из n последующих
# строк записаны 6 различных целых чисел bj (1≤bj≤32) — числа, записанные на очередном
# лотерейном билета. Формат вывода. Данные должны выводиться(сохраняться) в файл
# output.txt. Выведите n строк. Для каждого лотерейного билета в порядке следования во
# входных данных выведите строку Lucky, если билет выигрышный, иначе выведите Unlucky.

with open("input.txt", "r") as input_file:

    lucky_numbers = list(map(int, input_file.readline().split()))
    number_of_participants = int(input_file.readline())

    with open("output.txt", "w+") as output_file:
        for x in range(number_of_participants):

            count = 0
            ticket = list(map(int, input_file.readline().split()))

            for i in lucky_numbers:
                if i in ticket:
                    count += 1

            if count >= 3:
                output_file.write("Lucky\n")
            else:
                output_file.write("Unlucky\n")